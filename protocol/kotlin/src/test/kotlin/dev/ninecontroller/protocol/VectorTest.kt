/** Reproduces the JSON vectors in protocol/vectors, generated by the Rust reference implementation. */
class VectorTest {
    private val dir = File(System.getProperty("vectors.dir"))
    private fun load(name: String) = Json.parseToJsonElement(File(dir, "$name.json").readText()).jsonObject
    private fun JsonObject.hex(k: String) = this[k]!!.jsonPrimitive.content.hexToByteArray()
    private fun JsonObject.str(k: String) = this[k]!!.jsonPrimitive.content

    @Test fun noiseXxByteExact() {
        val v = load("noise_xx")
        val i = Handshake(true, KeyPair.fromSecret(v.hex("init_static"))).withFixedEphemeral(v.hex("init_ephemeral"))
        val r = Handshake(false, KeyPair.fromSecret(v.hex("resp_static"))).withFixedEphemeral(v.hex("resp_ephemeral"))
        assertContentEquals(v.hex("init_static_pub"), KeyPair.fromSecret(v.hex("init_static")).public)
        val msgs = v["messages"]!!.jsonArray.map { it.jsonObject }
        val m1 = i.writeMessage(msgs[0].hex("payload")); assertContentEquals(msgs[0].hex("ciphertext"), m1)
        assertContentEquals(msgs[0].hex("payload"), r.readMessage(m1))
        val m2 = r.writeMessage(msgs[1].hex("payload")); assertContentEquals(msgs[1].hex("ciphertext"), m2)
        assertContentEquals(msgs[1].hex("payload"), i.readMessage(m2))
        val m3 = i.writeMessage(msgs[2].hex("payload")); assertContentEquals(msgs[2].hex("ciphertext"), m3)
        assertContentEquals(msgs[2].hex("payload"), r.readMessage(m3))
        val ti = i.intoTransport(); val tr = r.intoTransport()
        assertContentEquals(v.hex("handshake_hash"), ti.handshakeHash)
        assertContentEquals(v.hex("resp_static_pub"), ti.remoteStatic)
        for (t in v["transport"]!!.jsonArray.map { it.jsonObject }) {
            val (send, recv) = if (t.str("from") == "initiator") ti to tr else tr to ti
            val ct = send.encrypt(t.hex("payload"))
            assertContentEquals(t.hex("ciphertext"), ct)
            assertContentEquals(t.hex("payload"), recv.decrypt(ct))
        }
    }

    @Test fun framesByteExactAndRejections() {
        val v = load("frames")
        val key = v.hex("key")
        for (c in v["valid"]!!.jsonArray.map { it.jsonObject }) {
            val type = PacketType.of(c["type"]!!.jsonPrimitive.int)!!
            val h = Header(type, c["session_id"]!!.jsonPrimitive.long.toInt(), c["counter"]!!.jsonPrimitive.long)
            assertContentEquals(c.hex("datagram"), Datagram.seal(key, h, c.hex("payload")), c.str("name"))
            val (h2, pt) = Datagram.open(key, c.hex("datagram"))
            assertEquals(h, h2)
            val f = c["fields"]!!.jsonObject
            when (type) {
                PacketType.INPUT -> {
                    val fr = InputFrame.decode(pt)
                    assertEquals(f["t_us"]!!.jsonPrimitive.long, fr.tUs)
                    assertEquals(InputState(f["buttons"]!!.jsonPrimitive.int, f["lx"]!!.jsonPrimitive.int, f["ly"]!!.jsonPrimitive.int,
                        f["rx"]!!.jsonPrimitive.int, f["ry"]!!.jsonPrimitive.int, f["lt"]!!.jsonPrimitive.int, f["rt"]!!.jsonPrimitive.int), fr.state)
                    assertContentEquals(c.hex("payload"), fr.encode())
                }
                PacketType.PONG -> assertEquals(Pong(99, 7, 1000, 1010), Pong.decode(pt))
                PacketType.FEEDBACK -> assertEquals(Feedback(1000, 65535, 120), Feedback.decode(pt))
                else -> Unit
            }
        }
        val expected = mapOf("too_short" to FrameError.TOO_SHORT, "auth" to FrameError.AUTH, "bad_magic" to FrameError.BAD_MAGIC,
            "bad_version" to FrameError.BAD_VERSION, "unknown_type" to FrameError.UNKNOWN_TYPE, "out_of_range" to FrameError.OUT_OF_RANGE,
            "bad_length" to FrameError.BAD_LENGTH)
        for (c in v["invalid"]!!.jsonArray.map { it.jsonObject }) {
            val e = assertFailsWith<FrameException>(c.str("name")) { InputFrame.decode(Datagram.open(key, c.hex("datagram")).second) }
            assertEquals(expected[c.str("error")], e.error, c.str("name"))
        }
        val fr = v["freshness"]!!.jsonObject
        val f = Freshness()
        val got = fr["counters"]!!.jsonArray.map { f.accept(it.jsonPrimitive.long) }
        assertEquals(fr["accepted"]!!.jsonArray.map { it.jsonPrimitive.boolean }, got)
        assertEquals(fr["lost"]!!.jsonPrimitive.long, f.lost)
        assertEquals(fr["stale"]!!.jsonPrimitive.long, f.stale)
    }

    @Test fun pairing() {
        val v = load("pairing")
        val h = v.hex("handshake_hash"); val na = v.hex("na"); val nb = v.hex("nb"); val tok = v.hex("token")
        assertContentEquals(v.hex("commitment"), Pairing.commitment(h, nb))
        assertTrue(Pairing.verifyCommitment(h, nb, v.hex("commitment")))
        assertEquals(v["sas"]!!.jsonPrimitive.int, Pairing.sasCode(h, na, nb))
        assertEquals(v.str("sas_display"), Pairing.formatCode(Pairing.sasCode(h, na, nb)))
        assertContentEquals(v.hex("qr_proof"), Pairing.qrProof(tok, h))
        val u = PairUri.parse(v.str("uri"))!!
        assertContentEquals(v.hex("uri_host_static"), u.hostStatic)
        assertEquals("Studio PC", u.name)
        assertEquals(v.str("uri"), u.toUri(), "URI encoding identical to Rust")
        assertEquals(v.str("host_id_of_uri_key"), Pairing.hostId(u.hostStatic))
        assertNull(PairUri.parse(v.str("uri").replace("v=1", "v=2")))
        assertNull(PairUri.parse("https://example.com/pair?v=1"))
    }

    @Test fun motion() {
        val v = load("motion")
        val p = v["params"]!!.jsonObject
        val m = MotionSettings(true, "lx", p["lockDeg"]!!.jsonPrimitive.double, p["deadzone"]!!.jsonPrimitive.double,
            p["sensitivity"]!!.jsonPrimitive.double, p["curve"]!!.jsonPrimitive.double, p["invert"]!!.jsonPrimitive.boolean,
            p["minCutoff"]!!.jsonPrimitive.double, p["beta"]!!.jsonPrimitive.double)
        val tol = 1e-9
        for (c in v["shape"]!!.jsonArray.map { it.jsonObject }) {
            val got = MotionMath.shape(c["delta_deg"]!!.jsonPrimitive.double, m)
            assertTrue(abs(got - c["out"]!!.jsonPrimitive.double) < tol, "shape ${c["delta_deg"]}: $got")
        }
        val s = Steering(m)
        s.setCenter(v["center_deg"]!!.jsonPrimitive.double)
        for ((i, c) in v["sequence"]!!.jsonArray.map { it.jsonObject }.withIndex()) {
            val g = c["g"]!!.jsonArray.map { it.jsonPrimitive.double }
            val got = s.update(g[0], g[1], g[2], c["t"]!!.jsonPrimitive.double)
            assertTrue(abs(got - c["out"]!!.jsonPrimitive.double) < tol, "sample $i: $got vs ${c["out"]}")
        }
    }

    @Test fun profiles() {
        val v = load("profiles")
        for (c in v["migration"]!!.jsonArray.map { it.jsonObject }) {
            val got = Profile.fromJson(c.str("input"))
            val want = Json { ignoreUnknownKeys = false }.decodeFromJsonElement(Profile.serializer(), c["expected"]!!)
            assertEquals(want, got)
        }
        for (c in v["invalid"]!!.jsonArray.map { it.jsonObject }) {
            assertFailsWith<ProfileException>(c.str("why")) { Profile.fromJson(c.str("json")) }
        }
        val presets = File(System.getProperty("profiles.dir")).listFiles { f -> f.extension == "json" }!!
        assertTrue(presets.size >= 3)
        for (f in presets) {
            val p = Profile.fromJson(f.readText())
            assertEquals(p, Profile.fromJson(p.toJson()), f.name)
        }
    }

    @Test fun controlJsonShapes() {
        assertEquals("""{"t":"open","resumeSlot":2}""", Control.Open(resumeSlot = 2).toJson().decodeToString())
        assertEquals("""{"t":"pair_code"}""", Control.PairCode.toJson().decodeToString())
        assertEquals(Control.Open(), Control.fromJson("""{"t":"open","extra":1}""".toByteArray()))
        val s = Control.fromJson("""{"t":"session","slot":1,"sessionId":4000000000,"udpPort":47900,"kIn":"a","kOut":"b","heartbeatMs":50,"idleHeartbeatMs":200,"timeoutMs":250}""".toByteArray())
        assertTrue(s is Control.Session && s.sessionId == 4000000000L && !s.toString().contains("kIn"))
    }
}
