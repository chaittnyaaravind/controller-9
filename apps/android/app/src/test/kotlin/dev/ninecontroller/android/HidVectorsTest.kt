package dev.ninecontroller.android

import dev.ninecontroller.android.input.RemoteHidReport
import dev.ninecontroller.android.input.XboxHidReport
import dev.ninecontroller.protocol.AXIS_MAX
import dev.ninecontroller.protocol.Button
import dev.ninecontroller.protocol.InputState
import dev.ninecontroller.protocol.TRIGGER_MAX
import org.junit.Assert.assertEquals
import org.junit.Test
import java.io.File

/**
 * The phone's exact Bluetooth HID bytes, for host-side simulation (tools/bt-host-sim): a Linux uhid
 * device is created with this report map and fed these reports, then SDL / evdev say what a computer
 * sees. Regenerate with `C9_WRITE_VECTORS=1 ./gradlew :app:testDebugUnitTest --tests '*HidVectorsTest*'`;
 * the test fails if the checked-in file is stale, like the protocol vectors.
 */
class HidVectorsTest {
    private fun hex(b: ByteArray) = b.joinToString("") { "%02x".format(it) }

    private fun vectors(): String {
        val steps = ArrayList<Pair<String, InputState>>()
        for (b in Button.entries) steps += b.id to InputState(buttons = b.mask)
        steps += "lx+" to InputState(lx = AXIS_MAX); steps += "lx-" to InputState(lx = -AXIS_MAX)
        steps += "ly+" to InputState(ly = AXIS_MAX); steps += "ly-" to InputState(ly = -AXIS_MAX)
        steps += "rx+" to InputState(rx = AXIS_MAX); steps += "rx-" to InputState(rx = -AXIS_MAX)
        steps += "ry+" to InputState(ry = AXIS_MAX); steps += "ry-" to InputState(ry = -AXIS_MAX)
        steps += "lt" to InputState(lt = TRIGGER_MAX); steps += "rt" to InputState(rt = TRIGGER_MAX)
        val r = RemoteHidReport
        val sb = StringBuilder("{\n")
        sb.append("  \"comment\": \"Generated by HidVectorsTest; do not edit. Reports exclude the report ID (HOGP carries it).\",\n")
        sb.append("  \"vendor\": ${XboxHidReport.VENDOR_ID}, \"product\": ${XboxHidReport.PRODUCT_ID}, \"version\": ${XboxHidReport.VERSION},\n")
        sb.append("  \"name\": \"Xbox Wireless Controller\",\n")
        sb.append("  \"report_map\": \"${hex(XboxHidReport.REPORT_MAP)}\",\n")
        sb.append("  \"report_map_remote\": \"${hex(XboxHidReport.REPORT_MAP + r.REPORT_MAP_EXTRA)}\",\n")
        sb.append("  \"input_id\": ${XboxHidReport.INPUT_ID},\n")
        sb.append("  \"neutral\": \"${hex(XboxHidReport.input(InputState.NEUTRAL))}\",\n")
        sb.append("  \"steps\": [\n")
        sb.append(steps.joinToString(",\n") { (k, s) -> "    {\"step\": \"$k\", \"report\": \"${hex(XboxHidReport.input(s))}\"}" })
        sb.append("\n  ],\n")
        sb.append("  \"remote\": {\n")
        sb.append("    \"keyboard_id\": ${r.KEYBOARD_ID}, \"key_a\": \"${hex(r.keyboard(0, 0x04))}\", \"key_up\": \"${hex(r.keyboard(0))}\",\n")
        sb.append("    \"mouse_id\": ${r.MOUSE_ID}, \"mouse_right_40\": \"${hex(r.mouse(0, 40, 0))}\",\n")
        sb.append("    \"consumer_id\": ${r.CONSUMER_ID}, \"volume_up\": \"${hex(r.consumer(r.VOLUME_UP))}\", \"consumer_up\": \"${hex(r.consumer(0))}\"\n")
        sb.append("  }\n}\n")
        return sb.toString()
    }

    @Test fun checkedInVectorsMatchTheEncoder() {
        val f = File("../../../tests/vectors/hid-xbox-ble.json")
        if (System.getenv("C9_WRITE_VECTORS") == "1") { f.parentFile.mkdirs(); f.writeText(vectors()) }
        assertEquals("tests/vectors/hid-xbox-ble.json is stale: regenerate (see class comment)", vectors(), f.readText())
    }
}
